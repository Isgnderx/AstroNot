// One-off: fetches the SPHEREx DR1 and QR3 SIA frame lists for BD+17 4708 and writes assets/tools/spherex-bd17-frames.js, the Forced Spectrophotometry example.
import { writeFileSync } from "node:fs";

const TARGET = { label: "BD+17_4708", ra: 332.882637, dec: 18.093128 };
const KEEP = ["obs_id", "access_url", "access_format", "energy_bandpassname", "obs_collection", "t_min", "t_max", "em_min", "em_max"];
const OUT = new URL("../assets/tools/spherex-bd17-frames.js", import.meta.url);

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i += 1; } else quoted = false; }
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i += 1;
      row.push(field); field = ""; rows.push(row); row = [];
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.length > 1 || r[0] !== "");
}

const quote = (v) => (/[",\r\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);

async function fetchFrames(collection) {
  const url = `https://irsa.ipac.caltech.edu/SIA?COLLECTION=${collection}&POS=CIRCLE%20${TARGET.ra}%20${TARGET.dec}%200.0001&MAXREC=2000&RESPONSEFORMAT=CSV`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${collection}: HTTP ${response.status}`);
  const rows = parseCsv(await response.text());
  const header = rows[0];
  const idx = KEEP.map((name) => {
    const i = header.indexOf(name);
    if (i < 0) throw new Error(`${collection}: column ${name} missing`);
    return i;
  });
  const lines = [KEEP.join(",")];
  for (const row of rows.slice(1)) lines.push(idx.map((i) => quote(row[i] ?? "")).join(","));
  return { name: `${collection}.csv`, rows: rows.length - 1, text: lines.join("\n") + "\n" };
}

const results = [await fetchFrames("spherex_dr1"), await fetchFrames("spherex_qr3")];
const data = {
  fetched: new Date().toISOString().slice(0, 10),
  target: TARGET,
  files: results.map(({ name, text }) => ({ name, text })),
};
const header = [
  "// Real SPHEREx frame lists for the Forced Spectrophotometry example: NASA/IPAC IRSA SIA (spherex_dr1 and spherex_qr3), cone of 0.0001 deg at BD+17 4708, MAXREC 2000.",
  `// Retrieved ${data.fetched}. Columns trimmed to ${KEEP.join(", ")}; values are IRSA's, unedited.`,
  "// Generated by scripts/make-bd17-frames.mjs; do not edit by hand.",
  "",
].join("\n");
writeFileSync(OUT, `${header}window.spherexBd17Frames = ${JSON.stringify(data)};\n`);
for (const r of results) console.log(`${r.name}: ${r.rows} rows`);
