// Builds assets/tools/constellations.js, the 88 IAU constellations for the Constellation Finder:
// official boundaries and names from d3-celestial (BSD-3-Clause; boundaries after the IAU lines by
// Roman 1987 via VizieR VI/49), plus the hand-written extras in scripts/constellations-extra.json
// (Azerbaijani names, Simplified Chinese, zodiac stick figures) and the six classic shapes already in
// tools/public-astronomy.js. Run: node scripts/make-constellations.mjs
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(import.meta.url);
const inputs = root + "tests/data/constellations/";
const bounds = JSON.parse(readFileSync(inputs + "constellations.bounds.json", "utf8"));
const names = JSON.parse(readFileSync(inputs + "constellations.json", "utf8"));
const extra = JSON.parse(readFileSync(root + "scripts/constellations-extra.json", "utf8"));
const astronomy = require(root + "tools/public-astronomy.js");

if (bounds.features.length !== names.features.length) throw new Error("bounds and names differ in length");
const simplified = (text) => [...text].map((ch) => extra.zhSimplified[ch] ?? ch).join("");
const toRa = (lon) => Math.round(((lon % 360) + 360) % 360 * 1e4) / 1e4;
const closed = (ring) => {
  const points = ring.map(([lon, lat]) => [toRa(lon), Math.round(lat * 1e4) / 1e4]);
  const [first, last] = [points[0], points[points.length - 1]];
  if (first[0] !== last[0] || first[1] !== last[1]) points.push([...first]);
  return points;
};

const classics = new Map(astronomy.constellations.map((entry) => [entry.name, entry]));
const byDesig = new Map();
names.features.forEach((feature, index) => {
  const p = feature.properties;
  const geometry = bounds.features[index].geometry;
  const rings = geometry.type === "Polygon" ? [geometry.coordinates[0]] : geometry.coordinates.map((poly) => poly[0]);
  const desig = p.desig;
  if (bounds.features[index].id !== feature.id) throw new Error("id mismatch at " + index);
  if (!byDesig.has(desig)) {
    const classic = classics.get(p.name) ?? null;
    const lines = extra.lines[desig] ?? (classic ? { anchor: classic.anchor, paths: classic.paths } : null);
    byDesig.set(desig, {
      desig, name: p.name, gen: p.gen,
      names: {
        en: p.name,
        az: extra.az[desig] ?? "",
        tr: extra.overrides[desig]?.tr ?? p.tr,
        ru: extra.overrides[desig]?.ru ?? p.ru,
        zh: simplified(extra.overrides[desig]?.zh ?? p.zh),
        es: extra.overrides[desig]?.es ?? p.es,
      },
      label: [toRa(feature.geometry.coordinates[0]), feature.geometry.coordinates[1]],
      polygons: [],
      zodiac: extra.zodiac[desig] ?? null,
      classic: extra.classic.includes(desig),
      lines: lines ? lines.paths : null,
      anchor: lines ? lines.anchor : null,
    });
  }
  byDesig.get(desig).polygons.push(...rings.map(closed));
});

const constellations = [...byDesig.values()].sort((a, b) => a.name.localeCompare(b.name, "en"));
if (constellations.length !== 88) throw new Error("expected 88 constellations, got " + constellations.length);
for (const entry of constellations) {
  for (const code of ["en", "az", "tr", "ru", "zh", "es"]) if (!entry.names[code]) throw new Error("missing " + code + " name for " + entry.desig);
}
const stars = { ...astronomy.guideStars, ...extra.stars };
for (const entry of constellations) {
  for (const name of (entry.lines ?? []).flat()) if (!stars[name]) throw new Error("unknown star " + name + " in " + entry.desig);
  if (entry.anchor && !(entry.lines ?? []).flat().includes(entry.anchor)) throw new Error("anchor not on a line: " + entry.desig);
}

const header = `// The 88 IAU constellations for the Constellation Finder. Generated by scripts/make-constellations.mjs; do not edit by hand.
// Boundaries (J2000, corner points of the IAU lines by Roman 1987 via VizieR VI/49) and names: d3-celestial by Olaf Frohn,
// BSD-3-Clause, https://github.com/ofrohn/d3-celestial (fetched 2026-11-15). Azerbaijani names, Simplified Chinese and the
// zodiac stick figures are hand-written (scripts/constellations-extra.json). Star positions: SIMBAD / Yale Bright Star Catalogue.
`;
const body = JSON.stringify({
  source: {
    boundaries: "IAU constellation boundaries (Roman 1987) via d3-celestial, BSD-3-Clause",
    names: "d3-celestial constellations.json; az by hand",
    licence: "BSD-3-Clause (d3-celestial data); see tests/data/constellations/LICENSE-d3-celestial.txt",
    fetched: "2026-11-15",
  },
  constellations,
  stars,
});
const out = root + "assets/tools/constellations.js";
writeFileSync(out, header + "window.AstroNotConstellations = " + body + ";\n");
console.log(constellations.length + " constellations, " + constellations.reduce((n, c) => n + c.polygons.length, 0) + " polygons, " +
  Object.keys(stars).length + " named stars, " + statSync(out).size + " bytes");
